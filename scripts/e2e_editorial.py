def compare(plans: dict[str, dict]) -> None:
    """The acceptance criterion the whole phase turns on.

    Three genres, three comparable libraries, three materially different edits.
    If this passes while the individual scenarios pass, the system cannot be
    described as "select clips and concatenate them" -- because the same
    pipeline, given the same kind of footage, produced three different cuts of
    it and the only thing that changed was a table of numbers.
    """
    step("8. COMPARISON - the genres produce materially different edits")

    shapes: dict[str, tuple[int, float, str]] = {}
    for name, plan in plans.items():
        editorial = plan.get("editorial")
        if not editorial or not editorial["segments"]:
            continue
        segments = editorial["segments"]
        mean = sum(segment["output_ms"] for segment in segments) / len(segments)
        shapes[name] = (len(segments), mean, editorial["pacing"]["curve"]["shape"])
        note(name, f"{len(segments)} shots, mean {mean:.0f} ms, "
                   f"pacing {editorial['pacing']['curve']['shape']}")

    if "nature" in shapes and "gaming" in shapes:
        check(
            "nature holds its shots longer than gaming",
            shapes["nature"][1] > shapes["gaming"][1] * 1.3,
            f"{shapes['nature'][1]:.0f} ms vs {shapes['gaming'][1]:.0f} ms",
        )
        check(
            "gaming cuts more often than nature",
            shapes["gaming"][0] > shapes["nature"][0],
            f"{shapes['gaming'][0]} vs {shapes['nature'][0]} shots",
        )
    if len(shapes) >= 2:
        check(
            "no two genres produced the same shape",
            len({(count, round(mean / 250)) for count, mean, _ in shapes.values()})
            == len(shapes),
            json.dumps({k: [v[0], round(v[1])] for k, v in shapes.items()}),
        )

    _report["comparison"] = {k: [v[0], round(v[1]), v[2]] for k, v in shapes.items()}


SCENARIOS = {"football": run_football, "nature": run_nature, "gaming": run_gaming}


def main() -> int:
    print("VisionForge - Phase 11 acceptance (creative auto-editing engine)")
    print("=" * 68)

    wanted = [name for name in sys.argv[1:] if name in SCENARIOS] or list(SCENARIOS)
    if len(wanted) > 1:
        print(
            "Running all three scenarios. On a memory-constrained machine, run "
            "them one at a time:\n"
            "    python scripts/e2e_editorial.py football\n"
        )

    try:
        httpx.get(f"{API}/health", timeout=10).raise_for_status()
    except Exception as exc:  # noqa: BLE001 - the script reports and exits
        print(f"API not reachable at {API}: {exc}")
        return 2

    plans: dict[str, dict] = {}
    for name in wanted:
        # One scenario at a time, deliberately. Each analyses twelve clips and
        # renders an MP4; running them concurrently would put three FFmpeg
        # encodes and three analyzer passes against 7.4 GB of RAM.
        plans[name] = SCENARIOS[name]()

    if len(plans) > 1:
        compare(plans)

    print("\n" + "=" * 68)
    print(json.dumps(_report, indent=2, default=str))
    if _failures:
        print(f"\n{len(_failures)} check(s) failed:")
        for failure in _failures:
            print(f"  - {failure}")
        return 1
    print("\nAll checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
